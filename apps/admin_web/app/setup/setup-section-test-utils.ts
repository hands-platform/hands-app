type RenderableComponent = (props: Record<string, unknown>) => unknown;

const DEFAULT_RENDERABLE_COMPONENTS = new Set([
  'AdminSection',
  'AdminActionCard',
  'AdminFormControlLink',
  'AdminMetricGrid',
  'AdminDetailGrid',
  'AdminSectionHeader',
  'CommandCopyRow',
  'MetricCard',
  'PathCopyRow',
  'StatusBadge',
  'StatusBadgeLink',
  'ReadinessRow',
  'SetupCommandList',
]);

export function textContent(value: unknown): string {
  value = resolveElement(value);
  if (value === null || value === undefined || typeof value === 'boolean') {
    return '';
  }
  if (typeof value === 'string' || typeof value === 'number') {
    return String(value);
  }
  if (Array.isArray(value)) {
    return value.map(textContent).join(' ');
  }

  const record = readRecord(value);
  const props = readRecord(record?.props);
  return textContent(props?.children);
}

export function hrefsIn(value: unknown): string[] {
  value = resolveElement(value);
  if (value === null || value === undefined || typeof value !== 'object') {
    return [];
  }
  if (Array.isArray(value)) {
    return value.flatMap(hrefsIn);
  }

  const record = readRecord(value);
  const props = readRecord(record?.props);
  const href = typeof props?.href === 'string' ? [props.href] : [];
  return [...href, ...hrefsIn(props?.children)];
}

export function classNamesIn(value: unknown): string[] {
  value = resolveElement(value);
  if (value === null || value === undefined || typeof value !== 'object') {
    return [];
  }
  if (Array.isArray(value)) {
    return value.flatMap(classNamesIn);
  }

  const record = readRecord(value);
  const props = readRecord(record?.props);
  const className = typeof props?.className === 'string' ? [props.className] : [];
  return [...className, ...classNamesIn(props?.children)];
}

function resolveElement(value: unknown): unknown {
  const record = readRecord(value);
  const props = readRecord(record?.props);
  const component = record?.type;
  if (typeof component !== 'function' || !DEFAULT_RENDERABLE_COMPONENTS.has(component.name)) {
    return value;
  }
  return resolveElement((component as RenderableComponent)(props ?? {}));
}

function readRecord(value: unknown): Record<string, unknown> | null {
  if (value && typeof value === 'object' && !Array.isArray(value)) {
    return value as Record<string, unknown>;
  }
  return null;
}
